static const uint8_t TARGET[8] = {
    0x1c, 0xa8, 0x77, 0xd4, 0x42, 0x0b, 0xe9, 0x35,
};

static int check(const char *s)
{
    if (strlen(s) != 8) return 0;                    /* ❶ */
    uint8_t acc = 0x5a;
    for (int i = 0; i < 8; i++) {
        uint8_t c = S[(uint8_t)s[i]] ^ (uint8_t)(0x13 + i) ^ acc;   /* ❷ */
        if (c != TARGET[i]) return 0;                /* ❸ */
        acc = c;                                     /* ❹ */
    }
    return 1;
}

/* Public sinks so angr's loader can resolve `win` and `lose` by name. */
__attribute__((noinline)) void win(void)
{
    puts("SOLVED");   /* unique marker grepped by `make test` */
}

__attribute__((noinline)) void lose(void)
{
    puts("nope");
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: %s <8-char-key>\n", argv[0]);
        return 2;
    }
    if (check(argv[1])) {
        win();
        return 0;
    }
    lose();
    return 1;
}
